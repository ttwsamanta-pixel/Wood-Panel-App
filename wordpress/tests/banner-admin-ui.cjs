const { chromium } = require('../../artifacts/ui-tools/node_modules/playwright');
(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1050}, acceptDownloads:true});
  await page.route('https://example.com/**', route => route.fulfill({path:'assets/home_banners/banner_1.png',contentType:'image/png'}));
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:8097/wp-login.php');
  await page.locator('#user_login').fill('banneradmin');
  await page.locator('#user_pass').fill('LocalBannerTest-927!');
  await Promise.all([page.waitForURL('**/wp-admin/**'),page.locator('#wp-submit').click()]);
  await page.goto('http://127.0.0.1:8097/wp-admin/edit.php?post_type=wpam_banner');
  if (!await page.getByRole('columnheader',{name:'Impressions / Clicks / CTR'}).count()) throw Error('Missing metrics columns');
  await page.screenshot({path:'artifacts/dual-edition/banner-list.png',fullPage:true});
  await page.goto('http://127.0.0.1:8097/wp-admin/post-new.php?post_type=wpam_banner');
  await page.locator('#title').fill('UI test footer');
  await page.locator('[name="wpam_ad[placement]"]').selectOption('footer_ads');
  await page.locator('[name="wpam_ad[size]"]').selectOption('350x100');
  await page.locator('#wpam-ad-image').fill('https://example.com/test-banner.png');
  await page.locator('#wpam-ad-link').fill('https://example.com/offer');
  await page.locator('#wpam-ad-order').fill('12');
  await page.locator('#wpam-ad-upload').click();
  await page.waitForSelector('.media-modal');
  await page.locator('.media-modal-close').click();
  await page.screenshot({path:'artifacts/dual-edition/banner-editor.png',fullPage:true});
  await page.locator('#publish:not(.disabled)').click();
  await page.waitForURL(url => url.pathname.endsWith('/post.php') && url.searchParams.get('message') === '6');
  if (await page.locator('[name="wpam_ad[size]"]').inputValue() !== '350x100') throw Error('Size did not save');
  if (await page.locator('#wpam-ad-link').inputValue() !== 'https://example.com/offer') throw Error('Link did not save');
  await page.locator('[name="wpam_ad[size]"]').selectOption('350x50');
  await Promise.all([page.waitForURL(url => url.searchParams.get('message') === '1'),page.locator('#publish').click()]);
  if (await page.locator('[name="wpam_ad[size]"]').inputValue() !== '350x50') throw Error('Edit failed');
  const id = new URL(page.url()).searchParams.get('post');
  const config = await (await page.request.get('http://127.0.0.1:8097/?rest_route=/wood-panel-app/v1/config')).json();
  const banner = config.footer_ads.find(b=>b.id===id);
  if (!banner) throw Error('Published banner not delivered by configuration');
  for (let i=0;i<8;i++) {
    const event={banner_id:id,placement:'footer_ads',token:banner.tracking_token,view_id:require('node:crypto').randomBytes(16).toString('hex'),type:'impression'};
    const response=await page.request.post('http://127.0.0.1:8097/?rest_route=/wood-panel-app/v1/ad-event',{data:event});
    if (!(await response.json()).recorded) throw Error('REST impression failed');
    if (i<2) await page.request.post('http://127.0.0.1:8097/?rest_route=/wood-panel-app/v1/ad-event',{data:{...event,type:'click'}});
  }
  await page.screenshot({path:'artifacts/dual-edition/banner-after-save.png',fullPage:true});
  await page.getByRole('link',{name:'View report',exact:true}).click();
  await page.waitForSelector('.wpam-chart svg');
  if (!(await page.locator('.wpam-metrics').innerText()).includes('25.00%')) throw Error('Report CTR does not reflect REST events');
  await page.screenshot({path:'artifacts/dual-edition/banner-report.png',fullPage:true});
  const download = page.waitForEvent('download');
  await page.getByRole('button',{name:'Export',exact:true}).click();
  const csv = await download;
  await csv.saveAs('artifacts/dual-edition/banner-report-test.csv');
  if (!(await require('node:fs/promises').readFile('artifacts/dual-edition/banner-report-test.csv','utf8')).includes('Impressions,Clicks')) throw Error('CSV missing headers');
  await page.goto('http://127.0.0.1:8097/wp-admin/admin.php?page=wpam-banner-reports');
  await page.screenshot({path:'artifacts/dual-edition/banner-reports.png',fullPage:true});
  if (!(await page.locator('body').innerText()).includes('UI test footer')) throw Error('Report list missing new banner');
  if (errors.length) throw Error(errors.join('\n'));
  await browser.close();
  console.log('Real WordPress UI: list, add, media picker, publish, edit, reports and CSV download passed.');
})().catch(e=>{console.error(e);process.exit(1)});
